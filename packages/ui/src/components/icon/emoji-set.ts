"use client";
import { translate } from "@workspace/ui/lib/i18n/runtime";

/** One Emoji: the character plus everything `Command` needs to filter it. */
export interface EmojiItem {
  /** The character itself — exactly what `NodeIcon.value` stores. */
  emoji: string;
  /** English name; the item's `SelectorGridItem.label` and accessible name. */
  name: string;
  /** Extra filter terms for `Command` (synonyms, close relations). */
  keywords: string[];
}

/** One category of {@link EMOJI_CATEGORIES}. */
export interface EmojiCategory {
  /** Stable id — also the anchor key of the bottom 分类条. */
  id: string;
  /** Display name of the category strip. */
  label: string;
  /** A representative Emoji drawn on the category strip. */
  icon: string;
  items: EmojiItem[];
}

/** `keywords` is written space-separated to keep a 300-line table readable. */
const e = (emoji: string, name: string, keywords: string): EmojiItem => ({
  emoji,
  name,
  keywords: keywords.split(" "),
});

