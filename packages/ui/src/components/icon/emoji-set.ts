/** Every entry of {@link EMOJI_CATEGORIES}, flattened (最近使用 / dedupe helper). */
export const EMOJI_SET: readonly EmojiItem[] = EMOJI_CATEGORIES.flatMap(
  (category) => category.items,
);

/** Looks a category up by its {@link EmojiCategory.id}; `undefined` when unknown. */
export function findEmojiCategory(id: string): EmojiCategory | undefined {
  return EMOJI_CATEGORIES.find((category) => category.id === id);
}
