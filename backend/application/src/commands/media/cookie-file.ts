import type { MediaSiteDefinition } from "@workspace/domain";

/**
 * Netscape `cookies.txt` handling for the media-site login flow.
 *
 * A browser extension exports every cookie of every site into one file. The
 * server must keep only the cookies of the sites it knows, and must be able to
 * cut the file into one per-site file again: a saved login belongs to exactly
 * one site, so a download for B 站 must never carry the YouTube cookie.
 *
 * Everything here is a pure function over text. The cipher and the database stay
 * in the repository port; this module only parses, filters, and serializes.
 *
 * The format is the one curl and yt-dlp read: one tab-separated line per cookie,
 * seven columns, `#` lines are comments. `HttpOnly` cookies are written with the
 * domain prefixed by `#HttpOnly_`, which is why the prefix is handled before the
 * comment check.
 */

/** One parsed cookie, with the columns the Netscape format defines. */
export interface ParsedCookie {
  /**
   * Cookie domain as the file wrote it. A leading dot means "and its
   * subdomains"; it is preserved so serialization round-trips.
   */
  domain: string;
  /** Column 2 of the format: the domain includes its subdomains. */
  includeSubdomains: boolean;
  /** Cookie path, usually `/`. */
  path: string;
  /** True when the cookie is only sent over HTTPS. */
  secure: boolean;
  /** Expiry as a unix timestamp in seconds; `0` means a session cookie. */
  expires: number;
  /** Cookie name. */
  name: string;
  /** Cookie value; may be empty. */
  value: string;
  /** True for a `#HttpOnly_` line. */
  httpOnly: boolean;
}

/** The prefix a Netscape file puts in front of an HttpOnly cookie's domain. */
const HTTP_ONLY_PREFIX = "#HttpOnly_";

/** Header written by browsers and by this product; both parser and writer agree. */
const FILE_HEADER = "# Netscape HTTP Cookie File";

/**
 * Parses a Netscape `cookies.txt`.
 *
 * A line that does not have seven tab-separated columns is skipped rather than
 * failing the whole import: browser extensions add their own comment lines and
 * one unreadable line must not throw away every cookie that is readable.
 */
export function parseCookieFile(text: string): ParsedCookie[] {
  const cookies: ParsedCookie[] = [];

  for (const rawLine of text.split(/\r?\n/)) {
    let line = rawLine.trimEnd();
    if (line.trim() === "") continue;

    let httpOnly = false;
    if (line.startsWith(HTTP_ONLY_PREFIX)) {
      // The prefix replaces the leading `#` of a comment, not adds to it:
      // strip it and treat the rest of the line as a normal cookie row.
      line = line.slice(HTTP_ONLY_PREFIX.length);
      httpOnly = true;
    } else if (line.trimStart().startsWith("#")) {
      continue;
    }

    const columns = line.split("\t");
    if (columns.length < 7) continue;

    const [domain, includeSubdomains, path, secure, expires, name] = columns;
    if (domain === undefined || name === undefined) continue;

    const cookie: ParsedCookie = {
      domain: domain.trim(),
      includeSubdomains: includeSubdomains?.trim().toUpperCase() === "TRUE",
      path: path ?? "/",
      secure: secure?.trim().toUpperCase() === "TRUE",
      expires: Number(expires ?? 0),
      name,
      // A cookie value is allowed to contain a tab; everything after the sixth
      // column belongs to it.
      value: columns.slice(6).join("\t"),
      httpOnly,
    };

    if (cookie.domain === "" || cookie.name === "") continue;
    if (!Number.isFinite(cookie.expires)) cookie.expires = 0;
    cookies.push(cookie);
  }

  return cookies;
}

/**
 * Serializes cookies back into a Netscape file.
 *
 * A saved login is stored as text, and yt-dlp is then handed it as a file; the
 * output therefore has to be exactly the format that was parsed. `HttpOnly` is
 * re-applied to the domain column, as browsers write it.
 */
export function serializeCookieFile(cookies: ParsedCookie[]): string {
  const lines = [
    FILE_HEADER,
    "# This file was generated by dBrainX and only contains the listed media sites.",
    "",
  ];

  for (const cookie of cookies) {
    const domain = `${cookie.httpOnly ? HTTP_ONLY_PREFIX : ""}${cookie.domain}`;
    lines.push(
      [
        domain,
        cookie.includeSubdomains ? "TRUE" : "FALSE",
        cookie.path || "/",
        cookie.secure ? "TRUE" : "FALSE",
        String(cookie.expires),
        cookie.name,
        cookie.value,
      ].join("\t"),
    );
  }

  return `${lines.join("\n")}\n`;
}

/** Host part of a cookie domain: lower case, no leading dot. */
export function cookieHost(domain: string): string {
  return domain.replace(/^\.+/, "").toLowerCase();
}

/** True when a cookie belongs to a site's hosts (exact or subdomain match). */
export function cookieMatchesSite(
  cookie: ParsedCookie,
  site: MediaSiteDefinition,
): boolean {
  const host = cookieHost(cookie.domain);
  return site.hosts.some(
    (siteHost) => host === siteHost || host.endsWith(`.${siteHost}`),
  );
}

/** Every cookie of one site, ready to be serialized into that site's login. */
export function cookiesForSite(
  cookies: ParsedCookie[],
  site: MediaSiteDefinition,
): ParsedCookie[] {
  return cookies.filter((cookie) => cookieMatchesSite(cookie, site));
}

/**
 * Cookie domains that match no listed site.
 *
 * These are dropped before anything is stored, and the UI tells the user which
 * domains were ignored rather than silently keeping a smaller file. Sorted and
 * de-duplicated so the message is stable.
 */
export function ignoredCookieDomains(
  cookies: ParsedCookie[],
  sites: MediaSiteDefinition[],
): string[] {
  const ignored = new Set<string>();
  for (const cookie of cookies) {
    const matched = sites.some((site) => cookieMatchesSite(cookie, site));
    if (!matched) ignored.add(cookieHost(cookie.domain));
  }
  return [...ignored].sort();
}
