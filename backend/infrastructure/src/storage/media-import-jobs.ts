import { randomBytes } from "node:crypto";
import {
  mkdir,
  readdir,
  readFile,
  rename,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import type {
  CreateMediaImportJobInput,
  IMediaImportJobStore,
  MediaImportJob,
  MediaImportJobPatch,
  MediaImportJobState,
} from "@workspace/domain";

/**
 * Root of the media import job tree.
 *
 * The directory is configurable because a job holds the bytes of one download in
 * flight: on a deployment the operator points this at a volume with room for it,
 * while a laptop keeps it in the temporary directory. A blank value counts as
 * unset, exactly like the other environment variables in this repository: a
 * compose file that passes `DBRAINX_MEDIA_IMPORT_DIR=` through verbatim must not
 * turn the root into an empty (relative) path.
 */
export function defaultMediaImportDir(): string {
  const configured = process.env.DBRAINX_MEDIA_IMPORT_DIR?.trim();
  return configured ? configured : join(tmpdir(), "dbrainx-media-imports");
}

/** File names the layout is made of. The application never sees these values. */
const SESSION_FILE = "session.json";
const DOWNLOAD_DIR = "download";

const JOB_STATES: readonly MediaImportJobState[] = [
  "running",
  "completed",
  "interrupted",
];

/**
 * A directory name that is safe to join into a path.
 *
 * The job id is generated by the client (it names the progress channel before
 * the mutation starts), so it must never reach `join` unchecked: a value like
 * `../../etc` would step out of the owner's directory. Restricting the segment
 * to letters, digits, `_` and `-` covers the UUID the client sends and nothing
 * that can traverse. The allowed alphabet is the one the application validates a
 * client-supplied job id with (`JOB_ID_PATTERN` in `media-import.service.ts`),
 * so a value the service accepts is never rejected here. The owner id is
 * verified by the token layer and has the same shape as a PocketBase id.
 */
function isSafeSegment(value: string): boolean {
  return /^[A-Za-z0-9_-]{1,128}$/.test(value);
}

/** True when the wrapped error means "this path is not there". */
function isMissing(error: unknown): boolean {
  return (error as NodeJS.ErrnoException).code === "ENOENT";
}

/**
 * A parsed `session.json`, or `null` when it is not a job record this store
 * wrote. A record that a half-finished write or an operator corrupted is not a
 * job: the sweep deletes its directory instead of trying to resume it.
 */
function isJobRecord(value: unknown): value is MediaImportJob {
  if (typeof value !== "object" || value === null) return false;
  const job = value as Record<string, unknown>;
  return (
    typeof job.jobId === "string" &&
    typeof job.ownerId === "string" &&
    typeof job.nodeId === "string" &&
    (job.kind === "video" || job.kind === "audio") &&
    typeof job.url === "string" &&
    typeof job.formatId === "string" &&
    typeof job.cookieVersion === "string" &&
    JOB_STATES.includes(job.state as MediaImportJobState) &&
    typeof job.stage === "string" &&
    typeof job.percent === "number" &&
    typeof job.createdAt === "string" &&
    !Number.isNaN(Date.parse(job.createdAt)) &&
    typeof job.updatedAt === "string" &&
    !Number.isNaN(Date.parse(job.updatedAt)) &&
    (job.result === null ||
      (typeof job.result === "object" && job.result !== null))
  );
}

/**
 * Resumable import jobs, spooled on the local file system.
 *
 * An import takes minutes, downloads up to the category ceiling, and must
 * survive the node dialog closing, the page reloading, and even the server
 * restarting. A table is the wrong shape for it: the payload is partly
 * downloaded bytes, which no record should hold, and yt-dlp resumes from the
 * files themselves (`source.mp4.part`). One directory per job keeps the record
 * and the bytes together, and deleting the directory is the whole cleanup:
 *
 * ```text
 * <root>/<ownerId>/<jobId>/
 *   session.json   the record below (nodeId, URL, state, result)
 *   download/      yt-dlp output: source.<ext>, partial files, thumbnail
 * ```
 *
 * Four rules are load-bearing:
 *
 * - **Owner scoping is mandatory.** Every method takes the verified `ownerId`,
 *   and a job of somebody else must be indistinguishable from a missing one:
 *   answering "forbidden" would confirm that the id exists.
 * - **`session.json` is replaced atomically.** Progress updates arrive while a
 *   client polls the job, so a reader that caught a half-written record would
 *   be told the job does not exist and lose its resume point. Every write goes
 *   to a unique temporary name and is moved into place with one `rename`.
 * - **A running job belongs to a live process.** `markInterrupted` runs once at
 *   startup: any job still marked `running` at that moment lost its process
 *   with the previous one, so it becomes `interrupted` and its partial download
 *   stays resumable.
 * - **Only `running` is never swept.** `sweep` deletes `interrupted` and
 *   `completed` jobs past their TTL, plus directories that have no readable
 *   record (a crash leftover). A corrupt record is deleted, never thrown: one
 *   bad directory must not stop the startup cleanup.
 *
 * The download itself lives in {@link FileMediaImportJobStore.workDir}, created
 * with the job directory, so the downloader writes into a path that already
 * exists and the caller deletes it with the job.
 */
export class FileMediaImportJobStore implements IMediaImportJobStore {
  private readonly rootDir: string;
  private readonly now: () => Date;

  /**
   * Plain field assignments rather than parameter properties: the co-located
   * test runs the file through Node's type-stripping loader (`node --test`),
   * which rejects TypeScript-only syntax that has a runtime effect.
   *
   * The clock is injectable for the same reason `FileUploadSessionStore` takes
   * one: TTL sweeping and "newest of a node" are time-based and must be
   * testable without sleeping.
   */
  constructor(
    rootDir: string = defaultMediaImportDir(),
    now: () => Date = () => new Date(),
  ) {
    this.rootDir = rootDir;
    this.now = now;
  }

  async create(input: CreateMediaImportJobInput): Promise<MediaImportJob> {
    this.assertSegment(input.ownerId, "owner id");
    this.assertSegment(input.jobId, "media import job id");

    const stamp = this.now().toISOString();
    const job: MediaImportJob = {
      jobId: input.jobId,
      ownerId: input.ownerId,
      nodeId: input.nodeId,
      kind: input.kind,
      url: input.url,
      formatId: input.formatId,
      cookieVersion: input.cookieVersion,
      state: "running",
      // The first thing an import does is download, so that is the stage a
      // freshly created job reports until the service updates it. Reporting a
      // stage rather than `""` keeps a reopened dialog from having to guess.
      stage: "downloading",
      percent: 0,
      createdAt: stamp,
      updatedAt: stamp,
      result: null,
    };

    const dir = this.jobDir(input.ownerId, input.jobId);
    // One recursive `mkdir` creates the root, the owner directory, the job
    // directory and the download directory. Resuming a job overwrites its
    // record but keeps whatever yt-dlp had already written here.
    await mkdir(join(dir, DOWNLOAD_DIR), { recursive: true });
    await this.writeSessionJson(dir, job);

    return job;
  }

  async findForNode(
    ownerId: string,
    nodeId: string,
  ): Promise<MediaImportJob | null> {
    if (!isSafeSegment(ownerId)) return null;

    let newest: MediaImportJob | null = null;
    for (const jobId of await this.listJobIds(ownerId)) {
      const job = await this.readJob(ownerId, jobId);
      if (!job || job.nodeId !== nodeId) continue;
      // ISO timestamps sort lexicographically, so a string comparison is enough.
      if (!newest || job.updatedAt > newest.updatedAt) newest = job;
    }
    return newest;
  }

  async read(ownerId: string, jobId: string): Promise<MediaImportJob | null> {
    if (!isSafeSegment(ownerId) || !isSafeSegment(jobId)) return null;
    return this.readJob(ownerId, jobId);
  }

  async update(
    ownerId: string,
    jobId: string,
    patch: MediaImportJobPatch,
  ): Promise<MediaImportJob | null> {
    if (!isSafeSegment(ownerId) || !isSafeSegment(jobId)) return null;

    const current = await this.readJob(ownerId, jobId);
    if (!current) return null;

    const next: MediaImportJob = {
      ...current,
      updatedAt: this.now().toISOString(),
    };
    if (patch.stage !== undefined) next.stage = patch.stage;
    if (patch.percent !== undefined) next.percent = patch.percent;
    if (patch.state !== undefined) next.state = patch.state;
    // `null` is a real patch value (a completed result the service clears), so
    // the check is left to `undefined` rather than truthiness.
    if (patch.result !== undefined) next.result = patch.result;

    try {
      await this.writeSessionJson(this.jobDir(ownerId, jobId), next);
    } catch (error) {
      // The sweep removed the directory between the read and the write. The
      // job is simply gone; the caller may ignore that.
      if (isMissing(error)) return null;
      throw error;
    }
    return next;
  }

  async remove(ownerId: string, jobId: string): Promise<void> {
    if (!isSafeSegment(ownerId) || !isSafeSegment(jobId)) return;
    // `force` makes a second call (and a sweep that already won the race) a
    // no-op, which is what "safe to call twice" promises.
    await rm(this.jobDir(ownerId, jobId), { recursive: true, force: true });
  }

  workDir(ownerId: string, jobId: string): string {
    // The path is returned synchronously and is about to be handed to yt-dlp, so
    // the segments are validated here as well rather than only in `create`.
    this.assertSegment(ownerId, "owner id");
    this.assertSegment(jobId, "media import job id");
    // Created by `create` (together with the job directory), so the downloader
    // can write straight into it; a resumed job already has it on disk.
    return join(this.jobDir(ownerId, jobId), DOWNLOAD_DIR);
  }

  async markInterrupted(): Promise<number> {
    const stamp = this.now().toISOString();
    let changed = 0;

    for (const ownerId of await this.listOwnerIds()) {
      for (const jobId of await this.listJobIds(ownerId)) {
        const job = await this.readJob(ownerId, jobId);
        if (!job || job.state !== "running") continue;

        const interrupted: MediaImportJob = {
          ...job,
          state: "interrupted",
          updatedAt: stamp,
        };
        try {
          await this.writeSessionJson(this.jobDir(ownerId, jobId), interrupted);
          changed += 1;
        } catch (error) {
          // A directory that disappeared mid-scan was already cleaned up by a
          // concurrent sweep; that is not a startup failure.
          if (!isMissing(error)) throw error;
        }
      }
    }

    return changed;
  }

  async sweep(ttlMs: number): Promise<number> {
    const now = this.now().getTime();
    let removed = 0;

    for (const ownerId of await this.listOwnerIds()) {
      for (const jobId of await this.listJobIds(ownerId)) {
        const job = await this.readJob(ownerId, jobId);
        // A directory without a readable record is a crash leftover: there is
        // no owner and no state to resume, so it is swept too. A corrupt record
        // is handled by the same branch rather than thrown.
        const expired =
          job === null ||
          (job.state !== "running" && now - Date.parse(job.updatedAt) > ttlMs);
        if (!expired) continue;

        try {
          await rm(this.jobDir(ownerId, jobId), {
            recursive: true,
            force: true,
          });
          removed += 1;
        } catch (error) {
          // Losing the race against a concurrent `remove` is not a failure.
          if (!isMissing(error)) throw error;
        }
      }
    }

    return removed;
  }

  /** `<root>/<ownerId>/<jobId>`; both segments are validated by the caller. */
  private jobDir(ownerId: string, jobId: string): string {
    return join(this.rootDir, ownerId, jobId);
  }

  /**
   * Reads a job by id without checking the owner, `null` when the file is not
   * there or does not describe this exact job. Owner scoping is enforced by the
   * caller, which reads from the owner's directory.
   */
  private async readJob(
    ownerId: string,
    jobId: string,
  ): Promise<MediaImportJob | null> {
    try {
      const raw = await readFile(
        join(this.jobDir(ownerId, jobId), SESSION_FILE),
        "utf8",
      );
      const parsed: unknown = JSON.parse(raw);
      if (!isJobRecord(parsed)) return null;
      // A record that names another directory (copied by hand, or the remnant
      // of an interrupted rename) is not this job.
      if (parsed.ownerId !== ownerId || parsed.jobId !== jobId) return null;
      return parsed;
    } catch {
      // Missing, unreadable or half-written: from the caller's point of view the
      // job simply does not exist.
      return null;
    }
  }

  private assertSegment(value: string, label: string): void {
    if (!isSafeSegment(value)) {
      // The value is not echoed: it may come from a request body.
      throw new Error(`Invalid ${label}`);
    }
  }

  /** Owner directory names under the root; missing root means no jobs yet. */
  private async listOwnerIds(): Promise<string[]> {
    return this.listDirectories(this.rootDir);
  }

  /** Job directory names under one owner; a missing owner means no jobs yet. */
  private async listJobIds(ownerId: string): Promise<string[]> {
    return this.listDirectories(join(this.rootDir, ownerId));
  }

  private async listDirectories(dir: string): Promise<string[]> {
    let entries;
    try {
      entries = await readdir(dir, { withFileTypes: true });
    } catch (error) {
      if (isMissing(error)) return [];
      throw error;
    }
    return entries
      .filter((entry) => entry.isDirectory() && isSafeSegment(entry.name))
      .map((entry) => entry.name);
  }

  private writeSessionJson(dir: string, job: MediaImportJob): Promise<void> {
    // Atomic replace, for the reason in the class comment: a client polls this
    // record while the import updates it, and a reader that catches a truncated
    // file treats the job as missing. `rename` on one file system is atomic, so
    // a reader sees the previous record or the new one, never half of either.
    // The temporary name is unique per writer so two concurrent writers cannot
    // move each other's file.
    const target = join(dir, SESSION_FILE);
    const staging = `${target}.${randomBytes(4).toString("hex")}.tmp`;

    return writeFile(staging, `${JSON.stringify(job, null, 2)}\n`, "utf8")
      .then(() => rename(staging, target))
      .catch(async (error: unknown) => {
        await rm(staging, { force: true }).catch(() => undefined);
        throw error;
      });
  }
}
