/**
 * Server-side state of one media import, kept so a closed dialog or a restarted
 * server can find its way back.
 *
 * An import takes minutes. The client that started it may close the node dialog,
 * reload the page, or lose the WebSocket, and the server itself may restart. The
 * job directory therefore outlives the request:
 *
 * ```text
 * <root>/<ownerId>/<jobId>/
 *   session.json      the record below (nodeId, URL, state, result)
 *   cookies.txt       only while a download runs, 0600
 *   download/         yt-dlp output: source.<ext>, partial files, thumbnail
 * ```
 *
 * Three rules are load-bearing:
 *
 * - **A finished job is short lived.** Once the client has written the result
 *   onto its node it confirms the job, and the directory is deleted. A failure or
 *   a cancellation deletes it immediately — a partly downloaded file is never
 *   kept for a retry, because the retry starts from a fresh directory.
 * - **Only an interrupted job is resumable.** A job whose process disappeared
 *   (server restart, crash) is marked `interrupted` at startup and kept for a
 *   day, so the user can press 「继续」 and yt-dlp continues its partial file.
 * - **Owner scoping is mandatory.** Every method takes the verified owner id; a
 *   job of somebody else is indistinguishable from a missing one.
 */

import type { MediaKind } from "./media-sites";
import type { MediaSubtitleTrack } from "./media-download";

/**
 * Lifecycle of one import.
 *
 * `running` and `interrupted` are the only states that keep a directory of
 * partial files; `completed` keeps the result until the client confirms it.
 */
export type MediaImportJobState = "running" | "completed" | "interrupted";

/** What a completed job hands back to the client, exactly once. */
export interface MediaImportJobResult {
  /** Name the stored source file was saved under. */
  fileName: string;
  /** Root-relative address of the stored source file. */
  url: string;
  /** Address of the stored cover / poster frame, `""` when there is none. */
  coverUrl: string;
  /** Address of the stored HLS playlist, `""` for audio and unpackaged video. */
  hlsUrl: string;
  /** Duration in seconds, `0` when unknown. */
  duration: number;
  /** Byte length of the stored source file. */
  fileSize: number;
  /** Title reported by the site. */
  title: string;
  /** Artist / uploader, `""` when unknown. */
  artist: string;
  /** Album, `""` when unknown. */
  album: string;
  /** Canonical page address of the media. */
  sourceUrl: string;
  /** yt-dlp extractor that answered. */
  extractorKey: string;
  /** Width in pixels of a video, `0` for audio. */
  width: number;
  /** Height in pixels of a video, `0` for audio. */
  height: number;
  /** Subtitle / lyric track, `null` when the site offered none. */
  subtitle: MediaSubtitleTrack | null;
}

/** One import job, as the store keeps it. */
export interface MediaImportJob {
  /** Random id generated by the server; names the progress channel too. */
  jobId: string;
  /** Verified owner. */
  ownerId: string;
  /** Node the result belongs to; one node runs at most one import at a time. */
  nodeId: string;
  /** What is being imported. */
  kind: MediaKind;
  /** Page URL the user pasted. */
  url: string;
  /** Chosen format id, `""` for "best available". */
  formatId: string;
  /** Tag of the cookie that was used, for the probe cache key. */
  cookieVersion: string;
  /** Current lifecycle state. */
  state: MediaImportJobState;
  /** Phase the server was last working on, for a resumed bar. */
  stage: string;
  /** Last reported overall completion, `0`–`100`. */
  percent: number;
  /** ISO timestamp of creation. */
  createdAt: string;
  /** ISO timestamp of the last update. */
  updatedAt: string;
  /** Result, once `state` is `completed`; `null` otherwise. */
  result: MediaImportJobResult | null;
}

/** What a new job is created from. */
export interface CreateMediaImportJobInput {
  /** Random id generated by the application layer. */
  jobId: string;
  /** Verified owner. */
  ownerId: string;
  /** Node the result belongs to. */
  nodeId: string;
  /** What is being imported. */
  kind: MediaKind;
  /** Page URL the user pasted. */
  url: string;
  /** Chosen format id, `""` for "best available". */
  formatId: string;
  /** Tag of the cookie that will be used. */
  cookieVersion: string;
}

/** Fields a running job may update. */
export interface MediaImportJobPatch {
  stage?: string;
  percent?: number;
  state?: MediaImportJobState;
  result?: MediaImportJobResult | null;
}

/** The job store: one directory per job, one record per directory. */
export interface IMediaImportJobStore {
  /** Writes a fresh `running` job and its directory. */
  create(input: CreateMediaImportJobInput): Promise<MediaImportJob>;
  /** The newest job of one node, or `null` when the node has none. */
  findForNode(ownerId: string, nodeId: string): Promise<MediaImportJob | null>;
  /** One job by id, or `null` when it is gone or belongs to somebody else. */
  read(ownerId: string, jobId: string): Promise<MediaImportJob | null>;
  /** Updates a job; a missing one is an error the caller may ignore. */
  update(
    ownerId: string,
    jobId: string,
    patch: MediaImportJobPatch,
  ): Promise<MediaImportJob | null>;
  /** Deletes the job directory and its record. Safe to call twice. */
  remove(ownerId: string, jobId: string): Promise<void>;
  /** Directory yt-dlp writes into for this job; created by {@link create}. */
  workDir(ownerId: string, jobId: string): string;
  /**
   * Startup sweep: every `running` job whose process is gone becomes
   * `interrupted`. Returns how many were changed.
   */
  markInterrupted(): Promise<number>;
  /**
   * Removes `interrupted` and `completed` jobs older than `ttlMs`, and any
   * directory with no readable record. Returns how many directories were
   * removed.
   */
  sweep(ttlMs: number): Promise<number>;
}
